import { chromium } from 'playwright'
const BASE = 'http://localhost:5173/'
const out = (k, v) => console.log(JSON.stringify({ [k]: v }))
const browser = await chromium.connectOverCDP('http://localhost:29229')
const ctx = browser.contexts()[0]
const page = await ctx.newPage()
await page.setViewportSize({ width: 390, height: 844 })
const dialogs = []; page.on('dialog', async (d) => { dialogs.push(d.message()); await d.accept() })
const errs = []; page.on('pageerror', (e) => errs.push(e.message.slice(0, 100)))
// a. Supabase injoignable au chargement (déjà connecté en Test A)
await page.route('**/*.supabase.co/**', (r) => r.abort())
await page.goto(BASE); await page.waitForTimeout(4000)
out('2a_supabase_down_body', (await page.locator('body').innerText()).slice(0, 250))
await page.unroute('**/*.supabase.co/**')
await page.reload(); await page.waitForTimeout(3000)
out('2a_recovered_h1', await page.locator('h1').first().innerText())
// b. titre très long
await page.getByRole('button', { name: /Nouvelle/ }).click(); await page.waitForTimeout(500)
const long = 'Ranger la chambre et aussi passer l aspirateur sous le lit puis trier les vieux cahiers et jeter les emballages ' + 'x'.repeat(120)
await page.getByPlaceholder('Ou écris autre chose…').fill(long)
await page.locator('.chip', { hasText: 'Test A (moi)' }).click()
await page.locator('.btn.big.block').last().click(); await page.waitForTimeout(2500)
const w = await page.evaluate(() => document.documentElement.scrollWidth)
out('2b_long_title_scrollWidth_vs_390', w)
await page.screenshot({ path: '/home/ubuntu/audit-t2-long.png' })
// c. roulette Test A + Test B
await page.getByRole('button', { name: /Nouvelle/ }).click(); await page.waitForTimeout(500)
await page.getByPlaceholder('Ou écris autre chose…').fill('AUDIT T2 roulette')
await page.getByRole('button', { name: /Roulette/ }).first().click()
await page.locator('.chip', { hasText: 'Test A (moi)' }).click()
await page.locator('.chip', { hasText: 'Test B' }).click()
await page.locator('.btn.big.block').last().click(); await page.waitForTimeout(1500)
out('2c_wheel_visible', await page.locator('canvas').count())
await page.waitForTimeout(5500)
out('2c_after_spin', (await page.locator('body').innerText()).match(/gagn|tiré|roulette|C'est .* qui/i)?.[0] ?? (await page.locator('body').innerText()).slice(0, 120))
await page.getByRole('button', { name: /Fermer|OK|Compris|Super/ }).first().click().catch(() => {})
await page.waitForTimeout(800)
// d. date limite passée (aujourd'hui 00:01)
await page.getByRole('button', { name: /Nouvelle/ }).click(); await page.waitForTimeout(500)
await page.getByPlaceholder('Ou écris autre chose…').fill('AUDIT T2 limite passée')
await page.locator('.chip', { hasText: 'Test A (moi)' }).click()
await page.getByRole('button', { name: /Avec limite/ }).click()
await page.locator('input[type=time]').last().fill('00:01')
await page.locator('.btn.big.block').last().click(); await page.waitForTimeout(2000)
out('2d_past_deadline_msg', (await page.locator('.banner').allInnerTexts()).join(' | ') || 'NO BANNER')
out('2d_created_anyway', await page.getByText('AUDIT T2 limite passée').count())
// e. Classement vide côté Test A ? et clic membre
await page.getByRole('button', { name: /Classement/ }).click(); await page.waitForTimeout(2000)
out('2e_classement', (await page.locator('.screen').innerText()).slice(0, 200))
out('dialogs', dialogs); out('pageerrors', errs)
await page.close(); process.exit(0)
